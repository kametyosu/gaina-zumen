import assert from "node:assert/strict";
import { newCable, newCore, editCore, editGroup, useWireTube, duplicateCable, mergeRead, confirmCable, catalogChange, defaults } from "../wiring/project.mjs";
import { buildRoutes, traceTerminal } from "../wiring/topology.mjs";
import { exportProject, inspectTemplate } from "../wiring/template-export.mjs";
import ExcelJS from "exceljs";
import JSZip from "jszip";
const g = newCable({ device: "MV-01W1", cores: [newCore()] });
editCore(g, g.cores[0], "wire", "001-02");
assert.equal(g.cores[0].tube, "001-02");
editCore(g, g.cores[0], "tube", "T-001");
editCore(g, g.cores[0], "wire", "0007");
assert.equal(g.cores[0].tube, "T-001");
useWireTube(g, g.cores[0]);
assert.equal(g.cores[0].tube, "0007");
editGroup(g, "cable", "MVVS");
assert.equal(g.device, "MV-01W1");
const copy = duplicateCable(g);
assert.notEqual(copy.id, g.id);
assert.notEqual(copy.cores[0].id, g.cores[0].id);
assert.equal(copy.status, "要確認");
assert.match(copy.duplicateWarning, /線番号/);
const raw = { id: "source-1", device: "READ", page: 7, cores: [{ id: "core-1", wire: "001", terminal: "" }, { id: "core-2", wire: "001", terminal: "" }] };
let current = mergeRead([], [raw]);
assert.equal(current[0].cores.length, 2);
editCore(current[0], current[0].cores[0], "wire", "MANUAL-001");
editCore(current[0], current[0].cores[1], "wire", "");
editGroup(current[0], "device", "MY-DEVICE");
current = mergeRead(current, [{ ...raw, device: "OCR-OTHER", cores: [{ id: "core-1", wire: "999" }, { id: "core-2", wire: "777" }] }]);
assert.equal(current[0].device, "MY-DEVICE");
assert.equal(current[0].cores[0].wire, "MANUAL-001");
assert.equal(current[0].cores[1].wire, "");
assert.equal(current[0].pending.length, 3);
confirmCable(current[0]);
assert.equal(current[0].cores[0].status, "確認済み");
const deleted = mergeRead([], [raw]);
deleted[0].deletedCoreIds = ["core-1"];
deleted[0].cores = deleted[0].cores.filter((c) => c.id !== "core-1");
assert.equal(mergeRead(deleted, [raw])[0].cores.length, 1);
const catalog = structuredClone(defaults);
catalogChange(catalog, "cable", "add", "CUSTOM");
catalogChange(catalog, "cable", "edit", "CUSTOM", "CUSTOM-2");
assert(catalog.cable.includes("CUSTOM-2"));
catalogChange(catalog, "cable", "delete", "CUSTOM-2");
assert(!catalog.cable.includes("CUSTOM-2"));
const line = (x, y, u, v) => ({ a: { x, y }, b: { x: u, y: v } });
let graph = buildRoutes({ lines: [line(0, 0, 10, 0), line(5, -5, 5, 5)], circles: [] });
assert.deepEqual(graph.edges, [[], []]);
graph = buildRoutes({ lines: [line(0, 0, 10, 0), line(10, 0, 10, 10)], circles: [] });
assert.deepEqual(graph.edges, [[1], [0]]);
graph = buildRoutes({ lines: [line(0, 0, 10, 0), line(5, -5, 5, 5)], circles: [], dots: [{ x: 5, y: 0 }] });
assert.deepEqual(graph.edges, [[1], [0]]);
graph = buildRoutes({ lines: [line(5, 10, 15, 10), line(19, 10, 25, 10)], circles: [{ x: 17, y: 10.04, r: 2, width: 4, height: 4 }] });
assert.equal(traceTerminal(graph, { x: 30, y: 10, r: 5 }, "left").terminal.x, 17);
const template = new ExcelJS.Workbook(), s = template.addWorksheet("CP-2");
s.getCell("A1").value = "原本";
s.mergeCells("A1:B2");
for (let r = 7; r <= 12; r++) for (let c = 1; c <= 53; c++) s.getCell(r, c).style = { font: { name: "ＭＳ ゴシック", size: 9 }, border: { bottom: { style: "thin" } } };
s.getColumn(1).width = 2.2;
s.pageSetup = { orientation: "landscape", paperSize: 9 };
s.pageSetup.printArea = "A1:BA12";
template.addWorksheet("PP-1").getCell("G3").value = "KEEP-ORIGINAL";
const bytes = await template.xlsx.writeBuffer();
assert.deepEqual((await inspectTemplate(bytes)).sheets, ["CP-2", "PP-1"]);
const project = newCable({ device: "MV-01W1", mark: "場所001", cable: "CVV", size: "1.25", coreCount: "12", shield: "あり", shieldConfig: { wire: "E", tube: "SH-01", terminal: "FG-01" }, notes: "備考", page: "7", drawing: "E-15", cores: Array.from({ length: 12 }, (_, i) => newCore({ color: String(i + 1), wire: i === 0 ? "0001" : "001-02", tubeMode: "custom", tube: "T-" + i, terminal: "TB-" + i })) });
const result = await exportProject([project], { templateBytes: bytes, pages: [7], fileName: "drawing.pdf" });
const before = await JSZip.loadAsync(bytes), after = await JSZip.loadAsync(result);
for (const name of Object.keys(before.files).filter((n) => !before.files[n].dir && !["xl/workbook.xml", "xl/_rels/workbook.xml.rels", "[Content_Types].xml"].includes(n))) assert.deepEqual(await before.file(name).async("uint8array"), await after.file(name).async("uint8array"), name + " must be byte-identical");
const out = new ExcelJS.Workbook();
await out.xlsx.load(result);
assert.equal(out.getWorksheet("PP-1").getCell("G3").value, "KEEP-ORIGINAL");
const main = out.getWorksheet("結線表_CP-2");
assert.equal(main.getCell("S5").value, "0001");
assert.equal(main.getCell("S7").value, "TB-0");
assert.equal(main.getCell("S11").value, "001-02");
assert.equal(main.getCell("Y9").value, "シールド");
assert.equal(main.getCell("Y11").value, "E");
assert.equal(main.getCell("Y13").value, "FG-01");
assert.match(main.getCell("L3").value, /シールドあり/);
assert.equal(out.getWorksheet("チューブ・端子明細").getCell("O2").value, "T-0");
assert.equal(main.pageSetup.orientation, "landscape");
assert.match(main.pageSetup.printArea, /BA14/);
const again = new ExcelJS.Workbook();
await again.xlsx.load(await exportProject([project], { templateBytes: result, pages: [7] }));
