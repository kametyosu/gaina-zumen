const root = resolve("dist"), server = createServer(async (req, res) => {
  try {
    let path = decodeURIComponent(new URL(req.url, "http://local").pathname);
    if (path.endsWith("/")) path += "index.html";
    const file = resolve(root, "." + path);
    if (!file.startsWith(root + "/")) throw Error();
    const data = await readFile(file);
    res.writeHead(200, { "content-type": { ".html": "text/html", ".mjs": "text/javascript", ".js": "text/javascript", ".css": "text/css", ".wasm": "application/wasm", ".gz": "application/gzip" }[extname(file)] || "application/octet-stream" });
    res.end(data);
  } catch {
    res.writeHead(404);
    res.end();
  }
});
